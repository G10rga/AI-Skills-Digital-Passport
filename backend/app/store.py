"""Persistence with two backends:

- PostgreSQL (production, self-hosted): DATABASE_URL=postgresql://...
- SQLite file (local dev/demo): fallback when DATABASE_URL is unset.

All SQL lives behind a tiny adapter (placeholder + dialect differences),
services never see which backend is active. Invariants either way:
one passport per student (student_id UNIQUE, passport_id PK), passport
identity written once and never updated, versions append-only.
"""
from __future__ import annotations

import json
import sqlite3
import threading
from pathlib import Path
from typing import Optional

SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS passports(
  passport_id TEXT PRIMARY KEY, student_id TEXT NOT NULL UNIQUE,
  first_name TEXT NOT NULL, last_name TEXT NOT NULL, email TEXT DEFAULT '',
  program TEXT DEFAULT '', education_level TEXT DEFAULT '',
  student_status TEXT DEFAULT '', first_issued TEXT DEFAULT '', public_slug TEXT DEFAULT '');
CREATE TABLE IF NOT EXISTS versions(
  id INTEGER PRIMARY KEY, passport_id TEXT NOT NULL REFERENCES passports(passport_id),
  version INT NOT NULL, issued_at TEXT NOT NULL, document_hash TEXT NOT NULL UNIQUE,
  verification_code TEXT NOT NULL UNIQUE, tx_hash TEXT NOT NULL, network TEXT NOT NULL,
  block_number INT NOT NULL, issuer_signature TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'ACTIVE', superseded_reason TEXT DEFAULT '',
  revoked_record_ids TEXT DEFAULT '[]', ipfs_cid TEXT DEFAULT '', signer_roles TEXT DEFAULT '[]',
  UNIQUE(passport_id, version));
CREATE TABLE IF NOT EXISTS version_skills(
  version_id INT NOT NULL REFERENCES versions(id), record_id TEXT NOT NULL,
  skill_id TEXT NOT NULL, skill_name TEXT DEFAULT '', skill_category TEXT DEFAULT '',
  badge_code TEXT DEFAULT '', skill_description TEXT DEFAULT '', date_earned TEXT DEFAULT '',
  PRIMARY KEY(version_id, record_id));
CREATE TABLE IF NOT EXISTS records(
  record_id TEXT PRIMARY KEY, student_id TEXT DEFAULT '', first_name TEXT DEFAULT '',
  last_name TEXT DEFAULT '', email TEXT DEFAULT '', program TEXT DEFAULT '',
  education_level TEXT DEFAULT '', passport_id TEXT DEFAULT '', first_issued TEXT DEFAULT '',
  student_status TEXT DEFAULT '', skill_id TEXT DEFAULT '', skill_name TEXT DEFAULT '',
  skill_category TEXT DEFAULT '', badge_code TEXT DEFAULT '', skill_description TEXT DEFAULT '',
  date_earned TEXT DEFAULT '', sync_status TEXT, synced_version TEXT, synced_at TEXT,
  sync_notes TEXT, sheet_row INT);
CREATE TABLE IF NOT EXISTS skill_requests(
  id INTEGER PRIMARY KEY, passport_id TEXT NOT NULL, student_id TEXT DEFAULT '',
  student_email TEXT DEFAULT '', skill_id TEXT NOT NULL, skill_name TEXT DEFAULT '',
  skill_category TEXT DEFAULT '', badge_code TEXT DEFAULT '', method TEXT NOT NULL,
  test_score INT, evidence_name TEXT DEFAULT '', evidence_hash TEXT DEFAULT '',
  evidence_url TEXT DEFAULT '', description TEXT DEFAULT '',
  status TEXT NOT NULL DEFAULT 'PENDING', admin_note TEXT DEFAULT '',
  record_id TEXT DEFAULT '', created_at TEXT NOT NULL, decided_at TEXT DEFAULT '',
  ai_summary TEXT DEFAULT '', ai_score INT, ai_model TEXT DEFAULT '', reviewer TEXT DEFAULT '',
  proof_links TEXT DEFAULT '[]', instructor_approval INT NOT NULL DEFAULT 0,
  career_center_approval INT NOT NULL DEFAULT 0,
  instructor_approver TEXT DEFAULT '', career_center_approver TEXT DEFAULT '');
CREATE TABLE IF NOT EXISTS verification_codes(
  email TEXT PRIMARY KEY, code_hash TEXT NOT NULL, expires_at TEXT NOT NULL,
  attempts INT NOT NULL DEFAULT 0, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS passport_requests(
  id INTEGER PRIMARY KEY, email TEXT NOT NULL, student_id TEXT DEFAULT '',
  first_name TEXT DEFAULT '', last_name TEXT DEFAULT '',
  status TEXT NOT NULL DEFAULT 'PENDING_STAFF', passport_id TEXT DEFAULT '',
  note TEXT DEFAULT '', created_at TEXT NOT NULL, decided_at TEXT DEFAULT '');
CREATE TABLE IF NOT EXISTS notifications(
  id INTEGER PRIMARY KEY, email TEXT NOT NULL, message TEXT NOT NULL,
  created_at TEXT NOT NULL, is_read INT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS review_flags(
  id INTEGER PRIMARY KEY, record_id TEXT NOT NULL, passport_id TEXT DEFAULT '',
  reason TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'FLAGGED',
  created_at TEXT NOT NULL, decided_at TEXT DEFAULT '');
CREATE INDEX IF NOT EXISTS idx_versions_passport ON versions(passport_id, version);
CREATE INDEX IF NOT EXISTS idx_records_passport ON records(passport_id, sync_status);
CREATE INDEX IF NOT EXISTS idx_requests_student ON skill_requests(student_email, status);
"""

PG_SCHEMA = SQLITE_SCHEMA.replace(
    "id INTEGER PRIMARY KEY,", "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")

RECORD_KEYS = ["studentId", "firstName", "lastName", "email", "program", "educationLevel",
               "passportId", "firstIssued", "studentStatus", "recordId", "skillId", "skillName",
               "skillCategory", "badgeCode", "skillDescription", "dateEarned",
               "syncStatus", "syncedVersion", "syncedAt", "syncNotes"]
RECORD_COLS = ["student_id", "first_name", "last_name", "email", "program", "education_level",
               "passport_id", "first_issued", "student_status", "record_id", "skill_id",
               "skill_name", "skill_category", "badge_code", "skill_description", "date_earned",
               "sync_status", "synced_version", "synced_at", "sync_notes", "sheet_row"]


class Store:
    def __init__(self, path: Path | None = None, database_url: str = ""):
        self._lock = threading.Lock()
        if database_url.startswith(("postgres://", "postgresql://")):
            try:
                import psycopg
                from psycopg.rows import dict_row
            except ImportError as e:
                raise RuntimeError("DATABASE_URL set but psycopg missing: pip install 'psycopg[binary]'") from e
            self.kind = "postgres"
            self.db = psycopg.connect(database_url, row_factory=dict_row, autocommit=True)
            schema = PG_SCHEMA
        else:
            assert path is not None
            path.parent.mkdir(parents=True, exist_ok=True)
            self.kind = "sqlite"
            self.db = sqlite3.connect(path, check_same_thread=False)
            self.db.row_factory = sqlite3.Row
            schema = SQLITE_SCHEMA
        for stmt in schema.split(";"):
            if stmt.strip():
                self._run(stmt)
        self._migrate()
        self._backfill_slugs()

    def _migrate(self) -> None:
        """Additive columns for pre-expansion databases (no migration tool)."""
        wanted = {
            "passports": {"public_slug": "TEXT DEFAULT ''"},
            "versions": {"status": "TEXT NOT NULL DEFAULT 'ACTIVE'",
                         "superseded_reason": "TEXT DEFAULT ''",
                         "revoked_record_ids": "TEXT DEFAULT '[]'",
                         "ipfs_cid": "TEXT DEFAULT ''", "signer_roles": "TEXT DEFAULT '[]'"},
            "skill_requests": {"ai_summary": "TEXT DEFAULT ''", "ai_score": "INT",
                               "ai_model": "TEXT DEFAULT ''", "reviewer": "TEXT DEFAULT ''",
                               "proof_links": "TEXT DEFAULT '[]'",
                               "instructor_approval": "INT NOT NULL DEFAULT 0",
                               "career_center_approval": "INT NOT NULL DEFAULT 0",
                               "instructor_approver": "TEXT DEFAULT ''",
                               "career_center_approver": "TEXT DEFAULT ''"},
        }
        for table, cols in wanted.items():
            if self.kind == "postgres":
                for col, ddl in cols.items():
                    self._run(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {col} {ddl}")
            else:
                existing = {r[1] for r in self.db.execute(f"PRAGMA table_info({table})").fetchall()}
                for col, ddl in cols.items():
                    if col not in existing:
                        self._run(f"ALTER TABLE {table} ADD COLUMN {col} {ddl}")

    @staticmethod
    def make_slug(first: str, last: str, passport_id: str) -> str:
        import hashlib, re as _re
        base = _re.sub(r"[^a-z0-9]+", "-", f"{first}-{last}".lower()).strip("-") or "student"
        digits = passport_id.replace("BTU-AI-", "")
        suffix = hashlib.sha256(passport_id.encode()).hexdigest()[:6]
        return f"{base}-{digits}-{suffix}"

    def _backfill_slugs(self) -> None:
        for p in self._all("SELECT passport_id, first_name, last_name FROM passports"
                           " WHERE public_slug IS NULL OR public_slug=''"):
            self._run("UPDATE passports SET public_slug=? WHERE passport_id=?",
                      (self.make_slug(p["first_name"], p["last_name"], p["passport_id"]),
                       p["passport_id"]))

    # -- adapter ------------------------------------------------------
    def _sql(self, sql: str) -> str:
        return sql.replace("?", "%s") if self.kind == "postgres" else sql

    def _run(self, sql: str, params: tuple = ()) -> None:
        with self._lock:
            try:
                cur = self.db.cursor()
                cur.execute(self._sql(sql), params)
                self.db.commit()
            except Exception:
                self.db.rollback()
                raise

    def _one(self, sql: str, params: tuple = ()) -> Optional[dict]:
        with self._lock:
            try:
                cur = self.db.cursor()
                cur.execute(self._sql(sql), params)
                row = cur.fetchone()
                return dict(row) if row else None
            except Exception:
                self.db.rollback()
                raise

    def _all(self, sql: str, params: tuple = ()) -> list[dict]:
        with self._lock:
            try:
                cur = self.db.cursor()
                cur.execute(self._sql(sql), params)
                return [dict(r) for r in cur.fetchall()]
            except Exception:
                self.db.rollback()
                raise

    def _insert_version(self, passport_id, version, issued_at, doc_hash, code,
                        tx_hash, network, block_number, signature, status="ACTIVE",
                        superseded_reason="", revoked_record_ids="[]", signer_roles="[]") -> int:
        sql = ("INSERT INTO versions(passport_id,version,issued_at,document_hash,verification_code,"
               "tx_hash,network,block_number,issuer_signature,status,superseded_reason,"
               "revoked_record_ids,signer_roles) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)")
        params = (passport_id, version, issued_at, doc_hash, code, tx_hash,
                  network, block_number, signature, status, superseded_reason,
                  revoked_record_ids, signer_roles)
        with self._lock:
            try:
                cur = self.db.cursor()
                if self.kind == "postgres":
                    cur.execute(self._sql(sql) + " RETURNING id", params)
                    vid = cur.fetchone()["id"]
                else:
                    cur.execute(sql, params)
                    vid = cur.lastrowid
                self.db.commit()
                return vid
            except Exception:
                self.db.rollback()
                raise

    def reset(self) -> None:
        for table in ("version_skills", "versions", "records", "passports", "skill_requests",
                      "verification_codes", "passport_requests", "notifications", "review_flags"):
            self._run(f"DELETE FROM {table}")

    # ---- passports -------------------------------------------------
    def register_passport(self, r: dict) -> None:
        """Create the passport identity if absent. Existing identity is
        NEVER overwritten (name / Passport ID / firstIssued are frozen)."""
        sql = "INSERT INTO passports VALUES (?,?,?,?,?,?,?,?,?,?)"
        if self.kind == "postgres":
            sql += " ON CONFLICT DO NOTHING"
        else:
            sql = sql.replace("INSERT INTO", "INSERT OR IGNORE INTO", 1)
        self._run(sql, (r.get("passportId", ""), r.get("studentId", ""), r.get("firstName", ""),
                        r.get("lastName", ""), r.get("email", ""), r.get("program", ""),
                        r.get("educationLevel", ""), r.get("studentStatus", ""),
                        r.get("firstIssued", ""),
                        self.make_slug(r.get("firstName", ""), r.get("lastName", ""),
                                       r.get("passportId", ""))))

    def get_passport(self, passport_id: str) -> Optional[dict]:
        return self._one("SELECT * FROM passports WHERE passport_id=?", (passport_id,))

    def get_passport_by_email(self, email: str) -> Optional[dict]:
        return self._one("SELECT * FROM passports WHERE lower(email)=lower(?)", (email,))

    def list_passports(self) -> list[dict]:
        return self._all("SELECT * FROM passports ORDER BY passport_id")

    # ---- versions --------------------------------------------------
    def _skills_of(self, version_id: int) -> list[dict]:
        return self._all(
            "SELECT record_id, skill_id, skill_name, skill_category, badge_code,"
            " skill_description, date_earned FROM version_skills WHERE version_id=?",
            (version_id,))

    def get_versions(self, passport_id: str) -> list[dict]:
        out = []
        for v in self._all("SELECT * FROM versions WHERE passport_id=? ORDER BY version",
                           (passport_id,)):
            v["skills"] = self._skills_of(v["id"])
            out.append(v)
        return out

    def find_version_by_code(self, code: str) -> Optional[tuple[dict, dict]]:
        v = self._one("SELECT * FROM versions WHERE verification_code=?", (code,))
        if not v:
            return None
        v["skills"] = self._skills_of(v["id"])
        return self.get_passport(v["passport_id"]), v

    def get_version(self, passport_id: str, version: int) -> Optional[dict]:
        rows = [v for v in self.get_versions(passport_id) if v["version"] == version]
        return rows[0] if rows else None

    def find_anchor(self, doc_hash: str) -> Optional[dict]:
        return self._one("SELECT * FROM versions WHERE document_hash=?", (doc_hash,))

    def get_passport_by_slug(self, slug: str) -> Optional[dict]:
        return self._one("SELECT * FROM passports WHERE public_slug=?", (slug,))

    def update_version_ipfs(self, passport_id: str, version: int, cid: str) -> Optional[dict]:
        self._run("UPDATE versions SET ipfs_cid=? WHERE passport_id=? AND version=?",
                  (cid, passport_id, version))
        return self.get_version(passport_id, version)

    # ---- anomaly review flags ---------------------------------------
    def add_flag(self, record_id: str, passport_id: str, reason: str, created_at: str) -> dict:
        existing = self._one("SELECT * FROM review_flags WHERE record_id=? AND status='FLAGGED'",
                             (record_id,))
        if existing:
            return existing
        return self._insert_row("review_flags", {"record_id": record_id,
                                "passport_id": passport_id, "reason": reason,
                                "status": "FLAGGED", "created_at": created_at, "decided_at": ""})

    def list_flags(self, status: str | None = None) -> list[dict]:
        if status:
            return self._all("SELECT * FROM review_flags WHERE status=? ORDER BY id DESC", (status,))
        return self._all("SELECT * FROM review_flags ORDER BY id DESC")

    def flag_for(self, record_id: str, status: str) -> Optional[dict]:
        return self._one("SELECT * FROM review_flags WHERE record_id=? AND status=?",
                         (record_id, status))

    def decide_flag(self, flag_id: int, status: str, decided_at: str) -> Optional[dict]:
        self._run("UPDATE review_flags SET status=?,decided_at=? WHERE id=?",
                  (status, decided_at, flag_id))
        return self._one("SELECT * FROM review_flags WHERE id=?", (flag_id,))

    def add_version(self, passport_id: str, version: int, issued_at: str, doc_hash: str,
                    code: str, tx_hash: str, network: str, block_number: int,
                    signature: str, skills: list[dict], status: str = "ACTIVE",
                    superseded_reason: str = "", revoked_record_ids: str = "[]",
                    signer_roles: str = "[]") -> None:
        vid = self._insert_version(passport_id, version, issued_at, doc_hash, code,
                                   tx_hash, network, block_number, signature, status,
                                   superseded_reason, revoked_record_ids, signer_roles)
        for s in skills:
            self._run("INSERT INTO version_skills VALUES (?,?,?,?,?,?,?,?)",
                      (vid, s["recordId"], s["skillId"], s["skillName"], s["skillCategory"],
                       s["badgeCode"], s["skillDescription"], s["dateEarned"]))

    # ---- sheet records (columns A-T) --------------------------------
    def upsert_record(self, r: dict, sheet_row: Optional[int] = None) -> None:
        """Insert a new sheet row, or refresh input columns A-P of an
        existing one. Q-T are system-managed: never overwritten on ingest."""
        if self._one("SELECT record_id FROM records WHERE record_id=?", (r.get("recordId", ""),)):
            self._run(
                "UPDATE records SET student_id=?,first_name=?,last_name=?,email=?,program=?,"
                "education_level=?,passport_id=?,first_issued=?,student_status=?,skill_id=?,"
                "skill_name=?,skill_category=?,badge_code=?,skill_description=?,date_earned=?,"
                "sheet_row=COALESCE(?,sheet_row) WHERE record_id=?",
                (r.get("studentId", ""), r.get("firstName", ""), r.get("lastName", ""), r.get("email", ""),
                 r.get("program", ""), r.get("educationLevel", ""), r.get("passportId", ""),
                 r.get("firstIssued", ""), r.get("studentStatus", ""), r.get("skillId", ""),
                 r.get("skillName", ""), r.get("skillCategory", ""), r.get("badgeCode", ""),
                 r.get("skillDescription", ""), r.get("dateEarned", ""), sheet_row, r.get("recordId", "")))
        else:
            vals = [r.get(k, "") for k in RECORD_KEYS[:16]]
            vals += [r.get("syncStatus"), r.get("syncedVersion"), r.get("syncedAt"),
                     r.get("syncNotes"), sheet_row]
            cols = RECORD_COLS
            self._run(f"INSERT INTO records({','.join(cols)}) VALUES ({','.join('?' * len(cols))})",
                      tuple(vals))

    def list_records(self) -> list[dict]:
        return [{**dict(zip(RECORD_KEYS, [row[c] for c in RECORD_COLS])), "sheetRow": row["sheet_row"]}
                for row in self._all("SELECT * FROM records ORDER BY record_id")]

    def pending_records(self) -> list[dict]:
        return [r for r in self.list_records() if r["syncStatus"] not in ("SYNCED", "DUPLICATE")]

    def update_record_sync(self, record_id: str, status: str, version: Optional[str],
                           synced_at: Optional[str], notes: Optional[str]) -> None:
        self._run("UPDATE records SET sync_status=?,synced_version=?,synced_at=?,sync_notes=?"
                  " WHERE record_id=?", (status, version, synced_at, notes, record_id))

    def update_records_passport_id(self, student_id: str, passport_id: str,
                                   first_issued: str = "") -> int:
        """Backfill identity onto records imported without one (e.g. an
        uploaded sheet for a brand-new student). Only touches rows that
        have no Passport ID yet."""
        rows = self._all("SELECT record_id FROM records WHERE student_id=?"
                         " AND (passport_id='' OR passport_id IS NULL)", (student_id,))
        for r in rows:
            self._run("UPDATE records SET passport_id=?,"
                      " first_issued=CASE WHEN first_issued='' THEN ? ELSE first_issued END"
                      " WHERE record_id=?", (passport_id, first_issued, r["record_id"]))
        return len(rows)

    def pending_count(self, passport_id: str) -> int:
        row = self._one("SELECT COUNT(*) c FROM records WHERE passport_id=? AND sync_status NOT IN"
                        " ('SYNCED','DUPLICATE')", (passport_id,))
        return int(row["c"]) if row else 0

    # ---- student skill requests --------------------------------------
    def create_request(self, r: dict) -> dict:
        cols = ["passport_id", "student_id", "student_email", "skill_id", "skill_name",
                "skill_category", "badge_code", "method", "test_score", "evidence_name",
                "evidence_hash", "evidence_url", "description", "status", "created_at",
                "ai_summary", "ai_score", "ai_model", "proof_links"]
        vals = tuple(r.get(c, "") if c not in ("test_score", "ai_score") else r.get(c) for c in cols)
        sql = f"INSERT INTO skill_requests({','.join(cols)}) VALUES ({','.join('?' * len(cols))})"
        with self._lock:
            try:
                cur = self.db.cursor()
                if self.kind == "postgres":
                    cur.execute(self._sql(sql) + " RETURNING id", vals)
                    rid = cur.fetchone()["id"]
                else:
                    cur.execute(sql, vals)
                    rid = cur.lastrowid
                self.db.commit()
            except Exception:
                self.db.rollback()
                raise
        return self.get_request(rid)

    def get_request(self, request_id: int) -> Optional[dict]:
        return self._one("SELECT * FROM skill_requests WHERE id=?", (request_id,))

    def list_requests(self, student_email: str | None = None) -> list[dict]:
        if student_email:
            return self._all("SELECT * FROM skill_requests WHERE lower(student_email)=lower(?)"
                             " ORDER BY id DESC", (student_email,))
        return self._all("SELECT * FROM skill_requests ORDER BY id DESC")

    def decide_request(self, request_id: int, status: str, note: str, decided_at: str,
                       record_id: str = "", reviewer: str = "") -> Optional[dict]:
        self._run("UPDATE skill_requests SET status=?,admin_note=?,decided_at=?,record_id=?,reviewer=?"
                  " WHERE id=?", (status, note, decided_at, record_id, reviewer, request_id))
        return self.get_request(request_id)

    def update_request(self, request_id: int, **fields) -> Optional[dict]:
        if not fields:
            return self.get_request(request_id)
        sets = ",".join(f"{k}=?" for k in fields)
        self._run(f"UPDATE skill_requests SET {sets} WHERE id=?",
                  (*fields.values(), request_id))
        return self.get_request(request_id)

    def attest_request(self, request_id: int, role_key: str, approver: str) -> Optional[dict]:
        col = "instructor" if role_key == "instructor" else "career_center"
        self._run(f"UPDATE skill_requests SET {col}_approval=1,{col}_approver=? WHERE id=?",
                  (approver, request_id))
        return self.get_request(request_id)


    # ---- account verification codes ----------------------------------
    def save_code(self, email: str, code_hash: str, expires_at: str, created_at: str) -> None:
        sql = ("INSERT INTO verification_codes(email,code_hash,expires_at,attempts,created_at)"
               " VALUES (?,?,?,0,?)")
        if self.kind == "postgres":
            sql += (" ON CONFLICT (email) DO UPDATE SET code_hash=EXCLUDED.code_hash,"
                    " expires_at=EXCLUDED.expires_at, attempts=0, created_at=EXCLUDED.created_at")
            self._run(sql, (email, code_hash, expires_at, created_at))
        else:
            self._run("DELETE FROM verification_codes WHERE email=?", (email,))
            self._run(sql, (email, code_hash, expires_at, created_at))

    def get_code(self, email: str) -> Optional[dict]:
        return self._one("SELECT * FROM verification_codes WHERE lower(email)=lower(?)", (email,))

    def bump_code_attempts(self, email: str) -> None:
        self._run("UPDATE verification_codes SET attempts=attempts+1 WHERE lower(email)=lower(?)",
                  (email,))

    def delete_code(self, email: str) -> None:
        self._run("DELETE FROM verification_codes WHERE lower(email)=lower(?)", (email,))

    def get_passport_by_student_id(self, student_id: str) -> Optional[dict]:
        return self._one("SELECT * FROM passports WHERE student_id=?", (student_id,))

    # ---- passport requests + notifications ----------------------------
    def _insert_row(self, table: str, data: dict) -> dict:
        cols = list(data)
        sql = f"INSERT INTO {table}({','.join(cols)}) VALUES ({','.join('?' * len(cols))})"
        with self._lock:
            try:
                cur = self.db.cursor()
                if self.kind == "postgres":
                    cur.execute(self._sql(sql) + " RETURNING id", tuple(data[c] for c in cols))
                    rid = cur.fetchone()["id"]
                else:
                    cur.execute(sql, tuple(data[c] for c in cols))
                    rid = cur.lastrowid
                self.db.commit()
            except Exception:
                self.db.rollback()
                raise
        return self._one(f"SELECT * FROM {table} WHERE id=?", (rid,))

    def create_passport_request(self, data: dict) -> dict:
        return self._insert_row("passport_requests", data)

    def latest_passport_request(self, email: str) -> Optional[dict]:
        return self._one("SELECT * FROM passport_requests WHERE lower(email)=lower(?)"
                         " ORDER BY id DESC", (email,))

    def list_passport_requests(self) -> list[dict]:
        return self._all("SELECT * FROM passport_requests ORDER BY id DESC")

    def get_passport_request(self, request_id: int) -> Optional[dict]:
        return self._one("SELECT * FROM passport_requests WHERE id=?", (request_id,))

    def decide_passport_request(self, request_id: int, status: str, note: str,
                                decided_at: str, passport_id: str = "") -> Optional[dict]:
        self._run("UPDATE passport_requests SET status=?,note=?,decided_at=?,passport_id=?"
                  " WHERE id=?", (status, note, decided_at, passport_id, request_id))
        return self.get_passport_request(request_id)

    def add_notification(self, email: str, message: str, created_at: str) -> None:
        self._run("INSERT INTO notifications(email,message,created_at) VALUES (?,?,?)",
                  (email, message, created_at))

    def list_notifications(self, email: str) -> list[dict]:
        return self._all("SELECT * FROM notifications WHERE lower(email)=lower(?)"
                         " ORDER BY id DESC", (email,))

def load_seed(path: Path) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8"))

